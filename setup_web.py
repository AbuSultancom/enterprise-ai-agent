@app.get("/setup", response_class=HTMLResponse)
async def setup_home(request: Request, step: int = 0, lang: str = "en"):
    sid, sess = _session(request)
    if lang not in STEPS:
        lang = "en"
    step = max(0, min(step, 8))

    # Pre-fill session with existing config on first visit
    if not sess:
        sessions[sid] = {
            "env":      _load_existing_env(),
            "settings": _load_existing_settings(),
            "schema":   _load_existing_schema(),
        }

    step_names = STEPS[lang]
    context = {
        "lang":         lang,
        "step":         step,
        "total_steps":  8,
        "step_names":   step_names,
        "step_title":   step_names[step] if step < len(step_names) else "Complete",
        "session":      json.dumps(sessions.get(sid, {}), ensure_ascii=False, indent=2),
        "admin_key":    secrets.token_urlsafe(40),
        "user_key":     secrets.token_urlsafe(40),
        "jwt_secret":   secrets.token_urlsafe(40),
        "enc_key":      secrets.token_urlsafe(40),
        "existing_env": sessions.get(sid, {}).get("env", {}),
    }
    html = _render_setup_page(context)
    resp = HTMLResponse(html)
    resp.set_cookie("setup_sid", sid, max_age=7200, httponly=True)
    return resp


@app.post("/setup")
async def handle_step(request: Request, step: int = 0, lang: str = "en"):
    sid, sess = _session(request)
    form = dict(await request.form())
    sess[f"step_{step}"] = form

    next_step = step + 1
    if next_step >= 8:
        await _finalize(sid)
        return RedirectResponse(url=f"/setup?step=8&lang={lang}", status_code=303)
    return RedirectResponse(url=f"/setup?step={next_step}&lang={lang}", status_code=303)


