def _session(request: Request) -> tuple[str, dict]:
    sid = request.cookies.get("setup_sid") or secrets.token_hex(20)
    if sid not in sessions:
        sessions[sid] = {}
    return sid, sessions[sid]


def _load_existing_env() -> dict[str, str]:
    env: dict[str, str] = {}
    if ENV_FILE.exists():
        for line in ENV_FILE.read_text(encoding="utf-8").splitlines():
            line = line.strip()
            if line and not line.startswith("#") and "=" in line:
                k, v = line.split("=", 1)
                env[k.strip()] = v.strip().strip('"').strip("'")
    return env


def _load_existing_settings() -> dict:
    for p in (SETTINGS_CFG, SETTINGS_FILE):
        if p.exists():
            try:
                return json.loads(p.read_text(encoding="utf-8"))
            except Exception:
                pass
    return {}


def _load_existing_schema() -> dict:
    if SCHEMA_FILE.exists():
        try:
            return json.loads(SCHEMA_FILE.read_text(encoding="utf-8"))
        except Exception:
            pass
    return {}


def _write_env(env_vars: dict[str, str]) -> None:
    lines = [
        "# Enterprise AI Agent — Environment Variables",
        f"# Generated by Web Setup: {datetime.now().isoformat()}",
        "# Do NOT commit this file to version control.",
        "",
    ]
    for k, v in sorted(env_vars.items()):
        if v:
            if any(c in str(v) for c in (" ", "#", "&", ";")):
                lines.append(f'{k}="{v}"')
            else:
                lines.append(f"{k}={v}")
    ENV_FILE.write_text("\n".join(lines) + "\n", encoding="utf-8")


def _write_settings(settings: dict) -> None:
    payload = json.dumps(settings, indent=2, ensure_ascii=False)
    SETTINGS_FILE.write_text(payload, encoding="utf-8")
    SETTINGS_CFG.write_text(payload, encoding="utf-8")


def _write_schema(schema: dict) -> None:
    SCHEMA_FILE.write_text(json.dumps(schema, indent=2, ensure_ascii=False), encoding="utf-8")


def _backup() -> str:
    BACKUP_DIR.mkdir(exist_ok=True)
    ts  = datetime.now().strftime("%Y%m%d_%H%M%S")
    dst = BACKUP_DIR / f"web_backup_{ts}"
    dst.mkdir(exist_ok=True)
    for f in (ENV_FILE, SETTINGS_FILE, SETTINGS_CFG, SCHEMA_FILE):
        if f.exists():
            shutil.copy2(f, dst / f.name)
    return str(dst)


# ── Connection string builder ─────────────────────────────────────────────

def _build_url(form: dict) -> str:
    db_type  = form.get("db_type", "mssql")
    if db_type == "sqlite":
        return f"sqlite:///{form.get('sqlite_path', 'data/accounting.db')}"

    host    = form.get("host", "localhost")
    port    = form.get("port", "1433")
    db_name = form.get("db_name", "")
    user    = form.get("username", "")
    pw      = urllib.parse.quote_plus(form.get("password", ""))
    user_at = f"{user}:{pw}@" if user else ""

    drv_map = {
        "oracle":     "oracle+oracledb",
        "mssql":      "mssql+pyodbc",
        "mysql":      "mysql+pymysql",
        "postgresql": "postgresql+psycopg2",
    }
    drv = drv_map.get(db_type, "oracle+oracledb")

    if db_type == "mssql":
        odbc = urllib.parse.quote_plus(form.get("odbc_driver", "ODBC Driver 18 for SQL Server"))
        return f"{drv}://{user_at}{host}:{port}/{db_name}?driver={odbc}&TrustServerCertificate=yes"
    if db_type == "oracle":
        service = db_name or "ORCL"
        return f"{drv}://{user_at}{host}:{port}/?service_name={service}"
    return f"{drv}://{user_at}{host}:{port}/{db_name}"


